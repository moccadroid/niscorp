import { describe, it, expect, afterEach } from 'vitest';
import { PGlite } from '@electric-sql/pglite';
import { createPglitePool } from '../../src/adapters/pglite/index.js';
import { createPostgresAdapter } from '../../src/adapters/postgres/index.js';
import { createQueryEngine } from '../../src/engine/runtime.js';
import { seedCache } from '../../src/cache/seed.js';
import { handleQuery } from '../../src/handler.js';
import type { QueryEngine } from '../../src/types.js';
import type { ScopePolicy } from '../../src/scope/scope.types.js';

const open: ScopePolicy = { default: 'allow', entities: {} };
const engines: QueryEngine[] = [];
afterEach(() => engines.splice(0).forEach((engine) => engine.rows.stop()));

const world = async (column: string) => {
  const db = new PGlite();
  await db.exec(`CREATE TABLE t (${column}, title TEXT)`);
  const engine = createQueryEngine({ adapter: createPostgresAdapter({ pool: createPglitePool(db) }) });
  engines.push(engine);
  await engine.introspect();
  await seedCache(engine.cache, [
    { fingerprint: 't/save', mutation: { op: 'upsert', table: 't', key: 'id', columns: { title: { $context: 'title' } } } },
    { fingerprint: 't/saveWithId', mutation: { op: 'upsert', table: 't', key: 'id', columns: { id: { $context: 'id' }, title: { $context: 'title' } } } },
  ]);
  const save = (fingerprint: string, policy: ScopePolicy = open) =>
    handleQuery({ engine, locked: true, mutations: { client: db, policy } }, { fingerprint, context: { id: null, title: 'new' } }, {});
  const count = async (): Promise<number> => Number((await db.query<{ n: number }>('SELECT count(*)::int AS n FROM t')).rows[0]?.n);
  return { db, engine, save, count };
};

describe('an upsert whose key is null', () => {
  it('updates no row where the database cannot make the key, and inserts once it can', async () => {
    const { db, engine, save, count } = await world('id TEXT PRIMARY KEY');
    expect(await save('t/save')).toEqual({ status: 200, body: { result: [] } });
    await db.exec('ALTER TABLE t ALTER COLUMN id SET DEFAULT gen_random_uuid()::text');
    await engine.introspect();
    expect(await save('t/save')).toMatchObject({ status: 200, body: { result: { title: 'new' } } });
    expect(await count()).toBe(1);
  });

  it.each(['id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY', 'id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'])('inserts on an identity key: %s', async (column) => {
    const { save } = await world(column);
    expect(await save('t/save')).toMatchObject({ status: 200, body: { result: { id: 1, title: 'new' } } });
  });

  it('updates no row where the entry writes the key itself', async () => {
    const { save, count } = await world('id UUID PRIMARY KEY DEFAULT gen_random_uuid()');
    expect(await save('t/saveWithId')).toEqual({ status: 200, body: { result: [] } });
    expect(await count()).toBe(0);
  });

  it('is refused, as an absent key is, for a caller who may update but not insert', async () => {
    const { save } = await world('id UUID PRIMARY KEY DEFAULT gen_random_uuid()');
    const updateOnly: ScopePolicy = { default: 'deny', entities: { t: { read: [], update: [] } } };
    expect(await save('t/save', updateOnly)).toMatchObject({ status: 400, body: { error: 'scope_denied' } });
  });
});
